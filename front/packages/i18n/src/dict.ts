const DICTS: Record<Locale, Dict> = { fa, en };

/** Translate a UI key. Unknown keys are a typing error (strict t()). */
export function t(locale: Locale, key: keyof Dict): string {
  return DICTS[locale][key];
}

/** Escrow wire state → localized label (CREATED → stateCreated …). */
export function escrowStateLabel(locale: Locale, state: string): string {
  const key = `state${state.charAt(0)}${state.slice(1).toLowerCase()}` as keyof Dict;
  const value = DICTS[locale][key];
  return typeof value === 'string' ? value : state;
}
