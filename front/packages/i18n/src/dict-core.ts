/** Build a strictly-typed translate function over one dictionary pair. */
export function makeT<K extends string>(dicts: Record<Locale, Record<K, string>>) {
  return (locale: Locale, key: K): string => dicts[locale][key];
}

/** Escrow wire state → localized label (CREATED → stateCreated …). */
export function escrowStateLabel(locale: Locale, state: string): string {
  const key = `state${state.charAt(0)}${state.slice(1).toLowerCase()}` as keyof DictCore;
  const value: unknown = (locale === 'fa' ? faCore : enCore)[key];
  return typeof value === 'string' ? value : state;
}
